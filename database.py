    def get_agent_config(self, agent_role: str) -> Optional[Dict[str, Any]]:
        """Retrieves the persistent configuration for a specific agent role."""
        cache_key = f"config_{agent_role}"
        cached = self._get_cached(cache_key)
        if cached:
            return cached

        session = self.Session()
        try:
            config = session.query(AgentConfigRecord).filter_by(agent_role=agent_role).first()
            if config:
                res = {
                    "agent_role": config.agent_role,
                    "system_prompt": config.system_prompt,
                    "temperature": config.temperature,
                    "max_tokens": config.max_tokens,
                    "version": config.version,
                    "updated_at": config.updated_at.isoformat() if config.updated_at else None
                }
                self._set_cache(cache_key, res)
                return res
            return None
        finally:
            session.close()

    def save_agent_config(self, agent_role: str, system_prompt: str, temperature: float = 0.7, max_tokens: int = 2000):
        """Saves or updates an agent's configuration and increments version."""
        session = self.Session()
        try:
            config = session.query(AgentConfigRecord).filter_by(agent_role=agent_role).first()
            if config:
                config.system_prompt = system_prompt
                config.temperature = temperature
                config.max_tokens = max_tokens
                config.version += 1
            else:
                config = AgentConfigRecord(
                    agent_role=agent_role,
                    system_prompt=system_prompt,
                    temperature=temperature,
                    max_tokens=max_tokens,
                    version=1
                )
                session.add(config)
            
            session.commit()
            self.clear_cache() # Invalidate cache on update
            logger.info(f"✓ Agent config persisted | Role: {agent_role} | Version: {config.version}")
            return config.version
        except Exception as e:
            session.rollback()
            logger.error(f"❌ Failed to save agent config for {agent_role}: {str(e)}")
            raise
        finally:
            session.close()

