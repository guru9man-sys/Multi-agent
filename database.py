    def save_user_preference(self, user_id: str, category: str, key: str, value: str):
        """Saves or updates a user preference."""
        session = self.Session()
        try:
            # Check if preference already exists
            pref = session.query(UserPreference).filter(
                UserPreference.user_id == user_id,
                UserPreference.preference_key == key
            ).first()

            if pref:
                pref.preference_value = value
                pref.updated_at = datetime.now()
            else:
                pref = UserPreference(
                    user_id=user_id,
                    category=category,
                    preference_key=key,
                    preference_value=value
                )
                session.add(pref)
            
            session.commit()
            session.close()
        except Exception as e:
            session.close()
            logger.error(f"Failed to save user preference: {e}")

    def get_user_preferences(self, user_id: str, category: Optional[str] = None) -> Dict[str, str]:
        """Retrieves all preferences for a user, optionally filtered by category."""
        session = self.Session()
        try:
            query = session.query(UserPreference).filter(UserPreference.user_id == user_id)
            if category:
                query = query.filter(UserPreference.category == category)
            
            prefs = query.all()
            result = {p.preference_key: p.preference_value for p in prefs}
            session.close()
            return result
        except Exception as e:
            session.close()
            logger.error(f"Failed to retrieve user preferences: {e}")
            return {}
