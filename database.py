class DBManager:
    """Singleton manager to handle SQLite sessions with thread-safe scoped sessions."""

    def __init__(self, db_url: str = None):
        if db_url is None:
            db_path = os.path.join(os.path.dirname(__file__), 'agent_system.db')
            db_url = f"sqlite:///{db_path}"

        self.engine = create_engine(db_url, echo=False, connect_args={"check_same_thread": False})
        Base.metadata.create_all(self.engine)
        
        # Phase 8: Optimization - Use scoped_session for thread-safety in async environments
        self.SessionFactory = sessionmaker(bind=self.engine)
        self.Session = scoped_session(self.SessionFactory)
        
        # Simple In-Memory Cache for frequent queries
        self._cache = {}
        self._cache_ttl = 300  # Cache expires in 5 minutes

    def _get_cached(self, key: str) -> Optional[Any]:
        """Retrieves item from cache if not expired."""
        if key in self._cache:
            val, timestamp = self._cache[key]
            if time.time() - timestamp < self._cache_ttl:
                return val
        return None

    def _set_cache(self, key: str, value: Any):
        """Stores item in cache with current timestamp."""
        self._cache[key] = (value, time.time())

    def clear_cache(self):
        """Clears all cached data."""
        self._cache = {}

    def save_message(self, session_id: str, role: str, content: str):
        """Saves a message to the conversation history."""
        session = self.Session()
        try:
            msg = ConversationMemory(session_id=session_id, role=role, content=content)
            session.add(msg)
            session.commit()
        except Exception as e:
            logger.error(f"Failed to save message: {e}")
            session.rollback()
        finally:
            self.Session.remove() # Crucial for scoped_session

    def get_history(self, session_id: str, limit: int = 10) -> List[Dict[str, str]]:
        """Retrieves the last N messages for a session."""
        session = self.Session()
        try:
            history = session.query(ConversationMemory)\
                .filter(ConversationMemory.session_id == session_id)\
                .order_by(ConversationMemory.timestamp.desc())\
                .limit(limit).all()
            return [{"role": h.role, "content": h.content} for h in reversed(history)]
        finally:
            self.Session.remove()

    def _validate_payload(self, payload: dict) -> bool:
        """Validate that payload has required fields."""
        if not isinstance(payload, dict):
            raise ValueError(f"Payload must be a dict, got {type(payload).__name__}")
        if not payload:
            raise ValueError("Payload cannot be empty")
        # Payload should have 'instruction' or 'user_input' for most tasks
        if 'instruction' not in payload and 'user_input' not in payload and 'content' not in payload:
            # Allow payloads without instruction for special cases (monitoring, etc.)
            logger.warning(f"⚠️ Payload lacks standard fields: {list(payload.keys())}")
        return True

    def _validate_artifacts(self, artifact_data: dict) -> bool:
        """Validate that artifacts have required structure."""
        if not isinstance(artifact_data, dict):
            raise ValueError(f"Artifact must be a dict, got {type(artifact_data).__name__}")
        artifacts = artifact_data.get('artifacts')
        if artifacts is None:
            raise ValueError("Artifacts field is required")
        if not artifacts and not isinstance(artifacts, dict):
            raise ValueError(f"Artifacts must be a dict, got {type(artifacts).__name__}")
        return True

    def create_task(self, task_data: dict) -> str:
        """Creates a new task record in the database."""
        session = self.Session()
        try:
            # Validate payload before saving
            payload = task_data.get('payload', {})
            self._validate_payload(payload)
            
            task_id = task_data.get('task_id', str(uuid.uuid4()))
            new_task = TaskRecord(
                task_id=task_id,
                priority=task_data.get('priority', 'medium'),
                agent_role=task_data.get('agent_role'),
                action=task_data.get('action'),
                payload=payload,
                constraints=task_data.get('constraints', []),
                status=task_data.get('status', 'pending'),
                escalated_to_cloud=task_data.get('escalated_to_cloud', False),
                parent_task_id=task_data.get('parent_task_id')
            )
            session.add(new_task)
            session.commit()
            logger.info(f"✓ Task created | ID: {task_id} | Agent: {task_data.get('agent_role')}")
            return task_id
        except Exception as e:
            session.rollback()
            logger.error(f"❌ Failed to create task: {str(e)}")
            raise
        finally:
            self.Session.remove()

    def update_task_status(self, task_id: str, status: str, reason: str = None):
        """Updates the status of a task and logs the transition."""
        session = self.Session()
        try:
            task = session.query(TaskRecord).filter_by(task_id=task_id).first()
            if task:
                old_status = task.status
                task.status = status
                session.commit()

                # Log the transition
                log = LogRecord(
                    log_id=str(uuid.uuid4()),
                    task_id=task_id,
                    old_status=old_status,
                    new_status=status,
                    reason=reason or "Status update"
                )
                session.add(log)
                session.commit()
        except Exception as e:
            logger.error(f"Failed to update task status for {task_id}: {e}")
            session.rollback()
        finally:
            self.Session.remove()

