    def get_execution_metrics_for_dag(self, dag_id: str, limit: int = 100) -> list:
        """Retrieves historical execution metrics for a DAG (Phase 7.2 Meta-Brain)."""
        session = self.Session()
        try:
            metrics = session.query(ExecutionMetricsRecord)\
                .filter(ExecutionMetricsRecord.task_id.like(f"{dag_id}%"))\
                .order_by(ExecutionMetricsRecord.created_at.desc())\
                .limit(limit).all()
            
            result = []
            for m in metrics:
                result.append({
                    'task_id': m.task_id,
                    'step_number': m.step_number,
                    'agent_role': m.agent_role,
                    'action': m.action,
                    'duration_seconds': m.duration_seconds,
                    'prompt_tokens': m.prompt_tokens,
                    'completion_tokens': m.completion_tokens,
                    'total_tokens': m.total_tokens,
                    'success': m.success,
                    'dependencies': m.dependencies,
                    'parallelizable_with': m.parallelizable_with,
                    'created_at': m.created_at.isoformat() if m.created_at else None
                })
            session.close()
            return result
        except Exception as e:
            session.close()
            logger.error(f"Failed to retrieve execution metrics: {e}")
            return []

